package com.hexbinoct.cg50

import android.content.ComponentName
import android.content.Context
import android.content.pm.PackageManager
import android.os.Build
import androidx.annotation.DrawableRes
import androidx.annotation.StringRes

/**
 * The launcher icon the user picked (settings → App icon…). Each icon is an <activity-alias>
 * of MainActivity in AndroidManifest.xml with the MAIN/LAUNCHER filter and its own icon;
 * exactly one alias is enabled, and that is the whole setting (nothing else is stored).
 * Porcelain's alias is enabled in the manifest, so it is the icon after a fresh install.
 * The icons themselves are generated by android/tools/make_launcher_icons.py.
 */
object AppIcons {

    class Icon(val alias: String, @StringRes val label: Int, @DrawableRes val mipmap: Int)

    val all = listOf(
        Icon("LauncherPorcelain", R.string.icon_porcelain, R.mipmap.ic_launcher_porcelain),
        Icon("LauncherPixelGraph", R.string.icon_pixelgraph, R.mipmap.ic_launcher_pixelgraph),
        Icon("LauncherCore", R.string.icon_core, R.mipmap.ic_launcher_core),
    )

    private fun component(ctx: Context, icon: Icon) =
        ComponentName(ctx.packageName, "${MainActivity::class.java.`package`!!.name}.${icon.alias}")

    /** Enabled now: set explicitly, or (never switched) as the manifest says. */
    private fun isEnabled(ctx: Context, icon: Icon): Boolean {
        val pm = ctx.packageManager
        val cn = component(ctx, icon)
        return when (pm.getComponentEnabledSetting(cn)) {
            PackageManager.COMPONENT_ENABLED_STATE_ENABLED -> true
            PackageManager.COMPONENT_ENABLED_STATE_DEFAULT -> try {
                if (Build.VERSION.SDK_INT >= 33) {
                    pm.getActivityInfo(cn, PackageManager.ComponentInfoFlags.of(PackageManager.MATCH_DISABLED_COMPONENTS.toLong())).enabled
                } else {
                    @Suppress("DEPRECATION") pm.getActivityInfo(cn, PackageManager.MATCH_DISABLED_COMPONENTS).enabled
                }
            } catch (_: PackageManager.NameNotFoundException) {
                false
            }
            else -> false
        }
    }

    fun current(ctx: Context): Icon = all.firstOrNull { isEnabled(ctx, it) } ?: all[0]

    /**
     * Shows [icon] in the launcher: its alias is enabled first, then the others are disabled, so
     * there is never a moment without a launcher entry. DONT_KILL_APP keeps the app running; the
     * launcher picks the change up from the package-changed broadcast (it can take a moment).
     */
    fun select(ctx: Context, icon: Icon) {
        val pm = ctx.packageManager
        pm.setComponentEnabledSetting(component(ctx, icon),
            PackageManager.COMPONENT_ENABLED_STATE_ENABLED, PackageManager.DONT_KILL_APP)
        for (other in all) {
            if (other !== icon && isEnabled(ctx, other)) {
                pm.setComponentEnabledSetting(component(ctx, other),
                    PackageManager.COMPONENT_ENABLED_STATE_DISABLED, PackageManager.DONT_KILL_APP)
            }
        }
    }
}
